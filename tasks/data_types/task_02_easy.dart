// Задача 2: Работа с числами (Легкая)
//
// ОПИСАНИЕ:
// В Dart есть два типа для работы с числами:
// - int: целые числа (1, 2, 100, -5)
// - double: числа с дробной частью (3.14, 2.5, -0.5)
// Важно понимать разницу и когда что использовать.
//
// ЧТО НУЖНО СДЕЛАТЬ:
// 1. Создайте int переменную apples = 10 (целых яблок)
// 2. Создайте int переменную people = 3 (количество людей)
// 3. Вычислите сколько целых яблок получит каждый: apples ~/ people
// 4. Вычислите остаток: apples % people
// 5. Создайте double переменную applesPerPerson = apples / people
// 6. Выведите результаты всех вычислений
//
// ЧТО МЫ ДОЛЖНЫ ПОЛУЧИТЬ:
// У нас есть 10 яблок на 3 человека
// Каждый получит: 3 целых яблока
// Останется: 1 яблоко
// Точное деление: 3.3333333333333335 яблока на человека

void main() {
  int apples = 10;
  int people = 3;
  double applesPerPerson = apples / people;
  print('Amount of apples for everyone:${apples~/people}. Leftover:${apples % people}. Apples per person:$applesPerPerson');

}
