// Задача 3: Изменение элементов списка (Легкая)
//
// ОПИСАНИЕ:
// Элементы списка можно изменять, присваивая новое значение по индексу.
// Также можно удалять элементы используя методы remove() и removeAt().
//
// ЧТО НУЖНО СДЕЛАТЬ:
// 1. Создайте список colors = ['красный', 'зелёный', 'синий', 'жёлтый', 'чёрный']
// 2. Выведите исходный список
// 3. Измените второй элемент (индекс 1) на 'оранжевый'
// 4. Измените последний элемент на 'белый'
// 5. Удалите элемент 'синий' используя remove()
// 6. Удалите элемент с индексом 0 используя removeAt()
// 7. Выведите итоговый список
//
// ЧТО МЫ ДОЛЖНЫ ПОЛУЧИТЬ:
// Исходные цвета: [красный, зелёный, синий, жёлтый, чёрный]
//
// После изменений:
// Изменён второй цвет на: оранжевый
// Изменён последний цвет на: белый
//
// После удалений:
// Удалён цвет: синий
// Удалён цвет с индексом 0
//
// Итоговые цвета: [оранжевый, жёлтый, белый]
//
void main() {
  List colors = ['red','green','blue','yellow','black'];
  print(colors);

  colors[1] = 'orange';
  colors[4] = 'white';
  colors.remove('blue');
  colors.removeAt(0);


  print(colors);

}
