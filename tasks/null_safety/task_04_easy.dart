// Задача 4: Оператор утверждения не-null (!) (Легкая)
//
// ОПИСАНИЕ:
// Оператор ! (null assertion operator) говорит компилятору "я уверен, что
// это значение не null". Используйте его только когда точно знаете,
// что значение не null. Иначе будет ошибка во время выполнения!
//
// ЧТО НУЖНО СДЕЛАТЬ:
// 1. Создайте nullable String? text = 'Dart'
// 2. Получите длину используя ! оператор: text!.length
// 3. Создайте nullable int? number = 42
// 4. Умножьте число на 2 используя !: number! * 2
// 5. Создайте nullable String? emptyText = null
// 6. Попробуйте использовать ! на null (закомментируйте - будет ошибка)
// 7. Покажите правильный способ - сначала проверить на null
//
// ЧТО МЫ ДОЛЖНЫ ПОЛУЧИТЬ:
// Текст: Dart
// Длина текста: 4
// (использован ! оператор, безопасно)
//
// Число: 42
// Число × 2: 84
// (использован ! оператор, безопасно)
//
// Пустой текст: null
// Попытка использовать ! на null:
// // emptyText!.length // ОШИБКА! Null check operator used on a null value
//
// Правильный способ с проверкой:
// Длина: null (проверено безопасно)
//
void main() {
  String? text = 'Dart';
  print('Length:${text!.length}');
  int? number = 42;
  print('Multiply number by two: ${number! * 2}');
  String? emptyText = null;
  print('Check for null value:${emptyText?.length}');

  // Попробуйте раскомментировать:
  // print(emptyText!.length); // Что произойдет?
}
