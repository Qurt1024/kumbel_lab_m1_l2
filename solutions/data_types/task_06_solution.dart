// Задача 6: Работа со строковой интерполяцией (Средняя) - РЕШЕНИЕ

void main() {
  // 1. Создаем переменные для интернет-магазина
  String productName = 'Ноутбук';
  double price = 75000.50;      // Цена за единицу
  int quantity = 2;              // Количество товара
  double discount = 0.15;        // 15% скидка (0.15 = 15/100)

  // 2. Вычисляем суммы
  // Общая сумма без скидки
  double totalPrice = price * quantity;

  // Сумма скидки (15% от общей суммы)
  double discountAmount = totalPrice * discount;

  // Итоговая сумма к оплате
  double finalPrice = totalPrice - discountAmount;

  // 3. Выводим чек используя интерполяцию
  // $переменная - для простых переменных
  // ${выражение} - для выражений и вычислений
  print('============== ЧЕК ==============');
  print('Товар: $productName');
  print('Цена за единицу: $price руб.');
  print('Количество: $quantity шт.');
  print('Сумма: $totalPrice руб.');

  // Используем ${} для вычислений прямо в строке
  print('Скидка ${discount * 100}%: -$discountAmount руб.');

  print('===================================');
  print('ИТОГО К ОПЛАТЕ: $finalPrice руб.');

  // ИНТЕРПОЛЯЦИЯ СТРОК:
  // $переменная - вставить значение переменной
  //   'Привет, $name' вместо 'Привет, ' + name
  //
  // ${выражение} - вставить результат вычисления
  //   'Сумма: ${a + b}' вместо 'Сумма: ' + (a + b).toString()
  //
  // ПРЕИМУЩЕСТВА:
  // 1. Код короче и читабельнее
  // 2. Не нужно вручную вызывать .toString()
  // 3. Можно вычислять прямо в строке

  // ПРИМЕРЫ:
  // int apples = 5;
  // int price = 50;
  // print('$apples яблок по $price руб = ${apples * price} руб');
  // Вывод: 5 яблок по 50 руб = 250 руб
}
