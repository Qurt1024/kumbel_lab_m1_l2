// Задача 1: Основные типы данных (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем String переменную с названием любимой книги
  // String используется для хранения текста (строк)
  String bookTitle = 'Гарри Поттер';

  // 2. Создаем int переменную с количеством страниц
  // int используется для целых чисел без дробной части
  int pages = 350;

  // 3. Создаем double переменную с рейтингом книги
  // double используется для чисел с дробной частью (десятичные числа)
  double rating = 4.8;

  // 4. Создаем bool переменную - прочитана ли книга
  // bool (boolean) может иметь только два значения: true (да) или false (нет)
  bool isRead = true;

  // 5. Выводим информацию о книге в красивом формате
  print('📖 Информация о книге');
  print('Название: $bookTitle');
  print('Страниц: $pages');
  print('Рейтинг: $rating из 5');

  // При выводе bool значения используем тернарный оператор
  // или можем напрямую вывести, но для красивого вывода:
  // true выводим как "да", false как "нет"
  print('Прочитано: ${isRead ? 'да' : 'нет'}');

  // ДОПОЛНИТЕЛЬНАЯ ИНФОРМАЦИЯ:
  // - String: любой текст в одинарных '' или двойных "" кавычках
  // - int: целые числа (1, 2, 100, -5, 0)
  // - double: числа с точкой (3.14, 0.5, -2.7)
  // - bool: только true или false (без кавычек!)
}
