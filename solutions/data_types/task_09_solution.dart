// Задача 9: Динамический тип dynamic (Сложная) - РЕШЕНИЕ

void main() {
  // 1. Создаем dynamic переменную
  // dynamic - это специальный тип, который может хранить ЛЮБОЕ значение
  // Тип может меняться во время выполнения программы
  dynamic data;

  // 2-3. Присваиваем строку и выводим
  data = 'Привет';
  print('Переменная data меняет тип:');
  print('Значение: $data, Тип: ${data.runtimeType}');

  // 4-5. Присваиваем целое число
  data = 42;
  print('Значение: $data, Тип: ${data.runtimeType}');

  // 6-7. Присваиваем дробное число
  data = 3.14;
  print('Значение: $data, Тип: ${data.runtimeType}');

  // 8-9. Присваиваем логическое значение
  data = true;
  print('Значение: $data, Тип: ${data.runtimeType}');

  // 10-11. Работаем с другими dynamic переменными
  print('');
  print('Работа с dynamic переменными:');

  dynamic num1 = 10;
  dynamic num2 = 20;
  print('num1 (dynamic): $num1');
  print('num2 (dynamic): $num2');
  print('Сумма: ${num1 + num2}');

  print('');
  dynamic text = 'Dart';
  print('text (dynamic): $text');
  print('Длина: ${text.length}');

  // 12. Объясняем проблемы с dynamic
  print('');
  print('Проблемы с dynamic:');
  dynamic value = 100;
  print('value (dynamic): $value');
  print('Попытка вызвать .length на числе может привести к ошибке!');

  // Раскомментируйте следующую строку чтобы увидеть ошибку:
  // print(value.length); // ОШИБКА! У чисел нет свойства length

  // ПОЧЕМУ dynamic ОПАСЕН?
  // 1. Компилятор не проверяет типы
  //    - можно вызвать методы, которых нет
  //    - ошибки обнаруживаются только во время выполнения
  //
  // 2. Нет автодополнения в редакторе
  //    - IDE не знает какие методы доступны
  //
  // 3. Код сложнее понимать и поддерживать
  //    - непонятно какой тип на самом деле
  //
  // 4. Легко допустить ошибку
  //    - dynamic x = 5;
  //    - x.toUpperCase(); // ОШИБКА во время выполнения!

  // КОГДА МОЖНО ИСПОЛЬЗОВАТЬ dynamic?
  // - Работа с JSON (данные из интернета)
  // - Интеграция с JavaScript кодом
  // - Когда тип действительно невозможно определить заранее
  //
  // НО: в большинстве случаев лучше использовать:
  // - конкретные типы (String, int, double, bool)
  // - Object или Object? если нужна гибкость
  // - Generic типы (<T>)

  // ПРИМЕР ПЛОХОГО КОДА:
  // dynamic data = getUserInput(); // Что это? String? int?
  // print(data.length); // Может сломаться!
  //
  // ПРИМЕР ХОРОШЕГО КОДА:
  // String data = getUserInput(); // Понятно что это String
  // print(data.length); // Безопасно!
}
