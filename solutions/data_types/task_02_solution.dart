// Задача 2: Работа с числами (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем переменные для задачи
  int apples = 10; // Целых яблок
  int people = 3;  // Количество людей

  // 2. Вычисляем сколько целых яблок получит каждый
  // Оператор ~/ - это целочисленное деление (результат всегда int)
  // 10 ~/ 3 = 3 (отбрасывает остаток)
  int applesPerPerson = apples ~/ people;

  // 3. Вычисляем остаток от деления
  // Оператор % - остаток от деления
  // 10 % 3 = 1 (потому что 10 = 3*3 + 1)
  int remainder = apples % people;

  // 4. Вычисляем точное деление (с дробной частью)
  // Оператор / - обычное деление (результат всегда double)
  // 10 / 3 = 3.333...
  double exactDivision = apples / people;

  // 5. Выводим результаты
  print('У нас есть $apples яблок на $people человека');
  print('Каждый получит: $applesPerPerson целых яблока');
  print('Останется: $remainder яблоко');
  print('Точное деление: $exactDivision яблока на человека');

  // ВАЖНЫЕ ОПЕРАТОРЫ ДЛЯ РАБОТЫ С ЧИСЛАМИ:
  // + сложение: 5 + 3 = 8
  // - вычитание: 5 - 3 = 2
  // * умножение: 5 * 3 = 15
  // / деление: 10 / 3 = 3.333... (результат double)
  // ~/ целочисленное деление: 10 ~/ 3 = 3 (результат int)
  // % остаток от деления: 10 % 3 = 1
}
