// Задача 8: Многострочные строки и специальные символы (Средняя) - РЕШЕНИЕ

void main() {
  // 1. Создаем многострочную строку используя тройные кавычки
  // Тройные кавычки ''' или """ позволяют писать текст на нескольких строках
  // Переносы строк сохраняются как в коде
  String poem = '''У лукоморья дуб зелёный;
Златая цепь на дубе том:
И днём и ночью кот учёный
Всё ходит по цепи кругом''';

  // 2. Создаем строку с табуляцией
  // \t - специальный символ табуляции (отступ как клавишей Tab)
  String tableHeader = 'Имя\tВозраст\tГород';

  // 3. Создаем строку с переносами строк используя \n
  // \n - специальный символ новой строки (как клавиша Enter)
  String linesWithN = 'Первая строка\nВторая строка\nТретья строка';

  // 4. Создаем строку с кавычками внутри
  // Способ 1: использовать разные типы кавычек
  String quoteInside = 'Он сказал: "Привет!"';

  // Способ 2: экранировать кавычки с помощью \
  // String quoteInside = "Он сказал: \"Привет!\"";

  // 5. Создаем сырую строку (raw string) с префиксом r
  // В сырой строке специальные символы не обрабатываются
  // \n, \t и другие остаются как есть
  String filePath = r'C:\Users\Documents\file.txt';

  // 6. Выводим все строки
  print('Многострочное стихотворение:');
  print(poem);
  print('');
  print('Таблица:');
  print(tableHeader);
  print('');
  print('Строки с \\n:');
  print(linesWithN);
  print('');
  print('Строка с кавычками: $quoteInside');
  print('');
  print('Путь: $filePath');

  // СПЕЦИАЛЬНЫЕ СИМВОЛЫ (ESCAPE-ПОСЛЕДОВАТЕЛЬНОСТИ):
  // \n - новая строка (перенос)
  // \t - табуляция (отступ)
  // \' - одинарная кавычка
  // \" - двойная кавычка
  // \\ - обратный слэш
  // \r - возврат каретки

  // МНОГОСТРОЧНЫЕ СТРОКИ:
  // Используйте ''' или """ для текста на нескольких строках
  // String text = '''
  //   Строка 1
  //   Строка 2
  //   Строка 3
  // ''';

  // СЫРЫЕ СТРОКИ (RAW STRINGS):
  // Префикс r отключает обработку специальных символов
  // Полезно для путей к файлам и регулярных выражений
  // r'C:\new\folder' - \n не превратится в перенос строки

  // ПРИМЕРЫ:
  // print('Строка 1\nСтрока 2');  // Две строки
  // print(r'Строка 1\nСтрока 2'); // Одна строка с текстом \n
}
