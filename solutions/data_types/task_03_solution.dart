// Задача 3: Работа со строками (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем переменные с именем и фамилией
  String firstName = 'Иван';
  String lastName = 'Иванов';

  // 2. Объединяем имя и фамилию через пробел
  // Способ 1: конкатенация (склеивание) через оператор +
  String fullName = firstName + ' ' + lastName;

  // Альтернативный способ - интерполяция:
  // String fullName = '$firstName $lastName';

  // 3. Создаем переменную с приветствием
  String greeting = 'Привет';

  // 4. Создаем полное приветствие, объединяя строки
  String fullGreeting = greeting + ', ' + fullName + '!';

  // 5. Получаем длину полного имени
  // Свойство .length возвращает количество символов в строке
  // В строке "Иван Иванов" 12 символов (включая пробел)
  int nameLength = fullName.length;

  // 6. Выводим результаты
  print('Имя: $firstName');
  print('Фамилия: $lastName');
  print('Полное имя: $fullName');
  print('Количество символов в имени: $nameLength');
  print('Приветствие: $fullGreeting');

  // ПОЛЕЗНЫЕ ОПЕРАЦИИ СО СТРОКАМИ:
  // + конкатенация: 'Привет' + ' ' + 'мир' = 'Привет мир'
  // .length - длина строки: 'Привет'.length = 6
  // .toUpperCase() - в верхний регистр: 'привет'.toUpperCase() = 'ПРИВЕТ'
  // .toLowerCase() - в нижний регистр: 'ПРИВЕТ'.toLowerCase() = 'привет'
  // .trim() - убрать пробелы с краев: '  привет  '.trim() = 'привет'
}
