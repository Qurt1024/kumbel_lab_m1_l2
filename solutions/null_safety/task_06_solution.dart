// Задача 6: Присваивание с проверкой на null (??=) (Средняя) - РЕШЕНИЕ

void main() {
  // 1. Создаем nullable String? переменную name
  // По умолчанию она содержит null
  String? name;

  print('Начальное значение name: $name');

  // 2. Используем оператор ??= для присваивания значения
  // Оператор ??= присваивает значение ТОЛЬКО если переменная равна null
  // Так как name = null, значение 'Гость' будет присвоено
  name ??= 'Гость';

  print("После ??= 'Гость': $name");

  // 4. Пытаемся присвоить другое значение 'Иван' используя ??=
  // Теперь name уже содержит 'Гость' (не null)
  // Поэтому присваивание НЕ произойдет - значение останется 'Гость'
  name ??= 'Иван';

  // 5. Выводим name - значение не изменилось
  print("После ??= 'Иван': $name (не изменилось)");

  print('');

  // Тест 1: Пустой Map
  print('Тест настроек 1 (пустой Map):');

  // Создаем пустой Map для настроек
  Map<String, String?> settings1 = {};

  print('Исходные настройки: $settings1');

  // Устанавливаем значения по умолчанию используя функцию
  setDefaultValues(settings1);

  print('После установки значений по умолчанию:');
  print(settings1);

  print('');

  // Тест 2: Частично заполненный Map
  print('Тест настроек 2 (частично заполненный):');

  // Создаем Map с некоторыми значениями
  // theme уже установлен в 'dark'
  // language установлен в null (явно)
  // fontSize отсутствует
  Map<String, String?> settings2 = {
    'theme': 'dark',
    'language': null,
  };

  print('Исходные настройки: $settings2');

  // Устанавливаем значения по умолчанию
  setDefaultValues(settings2);

  print('После установки значений по умолчанию:');
  print(settings2);
  print('(theme не изменился, language получил значение)');
}

// Функция setDefaultValues устанавливает значения по умолчанию для настроек
// Параметр settings - Map с nullable значениями String?
void setDefaultValues(Map<String, String?> settings) {
  // Используем оператор ??= для каждой настройки
  // Оператор ??= присваивает значение ТОЛЬКО если текущее значение null

  // Для 'theme': если ключа нет в Map или значение null, установим 'light'
  settings['theme'] ??= 'light';

  // Для 'language': если ключа нет в Map или значение null, установим 'ru'
  settings['language'] ??= 'ru';

  // Для 'fontSize': если ключа нет в Map или значение null, установим '14'
  settings['fontSize'] ??= '14';

  // ВАЖНО: Если значение уже установлено (не null), оно НЕ изменится
  // Например, если theme уже был 'dark', он останется 'dark'
}
