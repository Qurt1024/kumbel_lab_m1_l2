// Задача 2: Оператор проверки на null (??) (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем nullable String? переменную userName
  // Переменная не инициализирована, поэтому по умолчанию содержит null
  String? userName;

  print('userName: $userName');

  // 2. Используем оператор ?? (null-coalescing operator)
  // Оператор ?? проверяет левое значение на null
  // Если левое значение null, возвращается правое значение (значение по умолчанию)
  // Если левое значение НЕ null, возвращается левое значение
  String displayName = userName ?? 'Гость';

  // 3. Выводим displayName
  // Так как userName был null, displayName получил значение 'Гость'
  print('Отображаемое имя: $displayName');
  print('(использовано значение по умолчанию)');

  print('');

  // 4. Присваиваем userName значение 'Иван'
  userName = 'Иван';

  print('userName: $userName');

  // 5. Снова используем оператор ??
  // Теперь userName содержит 'Иван' (не null)
  // Поэтому displayName получит значение 'Иван', а не 'Гость'
  displayName = userName ?? 'Гость';

  // 6. Выводим displayName
  print('Отображаемое имя: $displayName');
  print('(использовано реальное значение)');

  print('');

  // 7. Создаем nullable int? переменную age
  // Переменная содержит null по умолчанию
  int? age;

  print('Возраст: $age');

  // 8. Выводим возраст с значением по умолчанию 18
  // Используем оператор ?? для задания значения по умолчанию
  // Так как age равен null, будет использовано значение 18
  int displayAge = age ?? 18;

  print('Отображаемый возраст: $displayAge');
  print('(использовано значение по умолчанию)');
}
