// Задача 9: Трансформация списков с map() и fold() (Сложная) - РЕШЕНИЕ

void main() {
  // 1. Создаем список prices
  var prices = [100.0, 250.0, 75.0, 300.0, 150.0];

  print('Исходные цены: $prices');

  // 2. Используем map() чтобы применить скидку 20% ко всем ценам
  // Метод map() преобразует каждый элемент списка
  // Скидка 20% означает, что цена становится 80% от исходной (умножаем на 0.8)
  // Используем .toList() чтобы преобразовать результат в список
  var discountedPrices = prices.map((price) => price * 0.8).toList();
  print('Цены со скидкой 20%: $discountedPrices');

  // 3. Используем fold() чтобы вычислить общую сумму со скидкой
  // Метод fold() сворачивает список к одному значению
  // Первый параметр (0.0) - начальное значение аккумулятора
  // Второй параметр - функция, которая добавляет каждый элемент к аккумулятору
  var totalSum = discountedPrices.fold(0.0, (sum, price) => sum + price);
  print('Общая сумма: $totalSum');
  print('');

  // 4. Создаем список names
  var names = ['иван', 'мария', 'петр'];

  print('Исходные имена: $names');

  // 5. Используем map() чтобы сделать первую букву заглавной
  // Для каждого имени берем первую букву в верхнем регистре
  // и добавляем остальную часть строки начиная со второго символа
  var capitalizedNames = names.map((name) {
    var firstLetter = name[0].toUpperCase();
    var restOfName = name.substring(1);
    return firstLetter + restOfName;
  }).toList();
  print('С заглавной буквы: $capitalizedNames');
  print('');

  // 6. Создаем список numbers
  var numbers = [1, 2, 3, 4, 5];

  print('Исходные числа: $numbers');

  // 7. Используем map() чтобы возвести каждое число в квадрат
  // Умножаем каждое число само на себя
  var squares = numbers.map((num) => num * num).toList();
  print('Квадраты чисел: $squares');

  // 8. Используем fold() чтобы вычислить произведение всех чисел
  // Начальное значение 1 (так как умножение на 0 дало бы 0)
  // Умножаем аккумулятор на каждый элемент
  var product = numbers.fold(1, (prod, num) => prod * num);
  print('Произведение всех чисел: $product');
}
