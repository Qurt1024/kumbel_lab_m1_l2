// Задача 1: Создание первого списка (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем список fruits с названиями 5 фруктов
  // List - это упорядоченная коллекция элементов
  // Элементы в списке нумеруются с 0 (первый элемент имеет индекс 0)
  var fruits = ['яблоко', 'банан', 'апельсин', 'груша', 'киви'];

  // 2. Выводим весь список
  // При выводе списка все элементы отображаются в квадратных скобках
  print('Список фруктов: $fruits');

  // 3. Выводим первый элемент списка (индекс 0)
  // Обращаемся к элементу по индексу используя квадратные скобки
  print('Первый фрукт: ${fruits[0]}');

  // 4. Выводим последний элемент списка (индекс 4)
  // Так как у нас 5 элементов (индексы от 0 до 4), последний элемент имеет индекс 4
  print('Последний фрукт: ${fruits[4]}');

  // 5. Выводим третий элемент списка (индекс 2)
  // Третий элемент по счету имеет индекс 2 (считаем с 0)
  print('Третий фрукт: ${fruits[2]}');

  // 6. Выводим количество элементов в списке
  // Свойство .length возвращает количество элементов в списке
  print('Всего фруктов: ${fruits.length}');
}
