// Задача 7: Методы поиска и фильтрации (Средняя) - РЕШЕНИЕ

void main() {
  // 1. Создаем список ages
  var ages = [15, 22, 18, 30, 17, 25, 16, 35, 20];

  print('Все возрасты: $ages');
  print('');

  // 2. Находим все возрасты >= 18 (совершеннолетние) используя where()
  // Метод where() фильтрует элементы по условию
  // Используем .toList() чтобы преобразовать результат в список
  var adults = ages.where((age) => age >= 18).toList();
  print('Совершеннолетние (>= 18): $adults');
  print('Количество: ${adults.length}');
  print('');

  // 3. Находим все возрасты < 18 (несовершеннолетние)
  var minors = ages.where((age) => age < 18).toList();
  print('Несовершеннолетние (< 18): $minors');
  print('Количество: ${minors.length}');
  print('');

  // 4. Находим первый возраст > 20 используя firstWhere()
  // Метод firstWhere() возвращает первый элемент, удовлетворяющий условию
  var firstOver20 = ages.firstWhere((age) => age > 20);
  print('Первый возраст > 20: $firstOver20');

  // 5. Проверяем, есть ли хотя бы один возраст > 30 используя any()
  // Метод any() возвращает true, если хотя бы один элемент удовлетворяет условию
  var hasOver30 = ages.any((age) => age > 30);
  print('Есть возраст > 30: $hasOver30');

  // 6. Проверяем, все ли возрасты > 10 используя every()
  // Метод every() возвращает true, если все элементы удовлетворяют условию
  var allOver10 = ages.every((age) => age > 10);
  print('Все возрасты > 10: $allOver10');
}
