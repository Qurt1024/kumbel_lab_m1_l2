// Задача 5: Работа с методами списков (Средняя) - РЕШЕНИЕ

void main() {
  // 1. Создаем список numbers
  var numbers = [5, 2, 8, 1, 9, 3, 7, 4, 6];

  print('Исходный список: $numbers');

  // 2. Выводим первый и последний элементы используя .first и .last
  // Свойство .first возвращает первый элемент списка
  // Свойство .last возвращает последний элемент списка
  print('Первый элемент: ${numbers.first}');
  print('Последний элемент: ${numbers.last}');
  print('');

  // 3. Создаем новый список reversedNumbers из развернутого numbers
  // Свойство .reversed возвращает обратный порядок элементов
  // Используем .toList() чтобы преобразовать результат в список
  var reversedNumbers = numbers.reversed.toList();
  print('Развернутый список: $reversedNumbers');
  print('');

  // 4. Сортируем numbers (по возрастанию) используя .sort()
  // Метод .sort() изменяет исходный список, сортируя его по возрастанию
  numbers.sort();
  print('Отсортированный (по возрастанию): $numbers');

  // 5. Создаем копию списка и сортируем по убыванию
  // Создаем копию списка используя List.from()
  var numbersCopy = List.from(numbers);
  // Сортируем копию по возрастанию
  numbersCopy.sort();
  // Разворачиваем список для получения сортировки по убыванию
  numbersCopy = numbersCopy.reversed.toList();
  print('Отсортированный (по убыванию): $numbersCopy');
  print('');

  // 6. Находим максимальное и минимальное значение в списке
  // После сортировки первый элемент - минимальный, последний - максимальный
  var minValue = numbers.first;
  var maxValue = numbers.last;
  print('Минимальное значение: $minValue');
  print('Максимальное значение: $maxValue');
}
