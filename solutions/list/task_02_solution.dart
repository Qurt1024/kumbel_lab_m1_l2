// Задача 2: Добавление элементов в список (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем пустой список tasks для задач
  // Пустой список создается с помощью пустых квадратных скобок []
  var tasks = [];

  // 2. Добавляем задачу "Сделать домашнее задание" используя add()
  // Метод add() добавляет один элемент в конец списка
  tasks.add('Сделать домашнее задание');

  // 3. Добавляем задачу "Купить продукты" используя add()
  tasks.add('Купить продукты');

  // 4. Добавляем задачу "Позвонить другу" используя add()
  tasks.add('Позвонить другу');

  // 5. Создаем список moreTasks с задачами
  var moreTasks = ['Прочитать книгу', 'Заниматься спортом'];

  // 6. Добавляем все задачи из moreTasks в tasks используя addAll()
  // Метод addAll() добавляет все элементы из другого списка в конец текущего списка
  tasks.addAll(moreTasks);

  // 7. Выводим итоговый список и его длину
  print('Список задач на сегодня:');
  // Выводим каждую задачу с номером (нумерация для пользователя начинается с 1)
  print('1. ${tasks[0]}');
  print('2. ${tasks[1]}');
  print('3. ${tasks[2]}');
  print('4. ${tasks[3]}');
  print('5. ${tasks[4]}');
  print('');
  print('Всего задач: ${tasks.length}');
}
