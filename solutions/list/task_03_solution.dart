// Задача 3: Изменение элементов списка (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем список colors
  var colors = ['красный', 'зелёный', 'синий', 'жёлтый', 'чёрный'];

  // 2. Выводим исходный список
  print('Исходные цвета: $colors');
  print('');

  // 3. Изменяем второй элемент (индекс 1) на 'оранжевый'
  // Присваиваем новое значение элементу по индексу
  print('После изменений:');
  colors[1] = 'оранжевый';
  print('Изменён второй цвет на: оранжевый');

  // 4. Изменяем последний элемент на 'белый'
  // Последний элемент имеет индекс 4 (длина списка 5, индексы от 0 до 4)
  colors[4] = 'белый';
  print('Изменён последний цвет на: белый');
  print('');

  // 5. Удаляем элемент 'синий' используя remove()
  // Метод remove() удаляет первое вхождение указанного элемента
  print('После удалений:');
  colors.remove('синий');
  print('Удалён цвет: синий');

  // 6. Удаляем элемент с индексом 0 используя removeAt()
  // Метод removeAt() удаляет элемент по указанному индексу
  colors.removeAt(0);
  print('Удалён цвет с индексом 0');
  print('');

  // 7. Выводим итоговый список
  print('Итоговые цвета: $colors');
}
