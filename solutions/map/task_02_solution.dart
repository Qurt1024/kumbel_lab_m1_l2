// Задача 2: Добавление и изменение элементов Map (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем пустой Map<String, int> для хранения баллов игроков
  // Map<String, int> означает, что ключи будут типа String, значения - int
  // {} создает пустой Map
  Map<String, int> scores = {};

  // 2-4. Добавляем игроков с их баллами
  // Для добавления используем синтаксис: mapName[key] = value
  scores['Иван'] = 100;   // добавляем игрока "Иван" с баллами 100
  scores['Мария'] = 150;  // добавляем игрока "Мария" с баллами 150
  scores['Петр'] = 120;   // добавляем игрока "Петр" с баллами 120

  // 5. Выводим начальную таблицу
  print('Начальная таблица игроков:');
  print('Иван: ${scores['Иван']} баллов');
  print('Мария: ${scores['Мария']} баллов');
  print('Петр: ${scores['Петр']} баллов');
  print('');

  print('Обновление баллов...');

  // 6. Увеличиваем баллы Ивана до 180
  // Сохраняем старое значение для демонстрации изменения
  var oldIvanScore = scores['Иван'];
  scores['Иван'] = 180;  // присваиваем новое значение
  print('Иван: $oldIvanScore -> ${scores['Иван']}');

  // 7. Увеличиваем баллы Марии на 50
  // Сначала получаем текущее значение, затем добавляем к нему 50
  var oldMariaScore = scores['Мария'];
  scores['Мария'] = scores['Мария']! + 50;  // ! говорит, что значение точно есть
  print('Мария: $oldMariaScore -> ${scores['Мария']}');
  print('');

  // 8. Выводим обновленную таблицу
  print('Финальная таблица:');
  print('Иван: ${scores['Иван']} баллов');
  print('Мария: ${scores['Мария']} баллов');
  print('Петр: ${scores['Петр']} баллов');
}
