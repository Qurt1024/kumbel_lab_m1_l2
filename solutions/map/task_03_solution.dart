// Задача 3: Удаление элементов из Map (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем Map<String, String> с контактами
  // Ключ - имя контакта, значение - номер телефона
  Map<String, String> contacts = {
    'Мама': '+7-900-111-22-33',
    'Папа': '+7-900-444-55-66',
    'Друг': '+7-900-777-88-99',
    'Врач': '+7-900-000-11-22',
    'Работа': '+7-900-333-44-55'
  };

  // 2. Выводим все контакты
  print('Список контактов:');
  print('Мама: ${contacts['Мама']}');
  print('Папа: ${contacts['Папа']}');
  print('Друг: ${contacts['Друг']}');
  print('Врач: ${contacts['Врач']}');
  print('Работа: ${contacts['Работа']}');
  print('Всего: ${contacts.length} контактов');
  print('');

  // 3. Удаляем контакт 'Работа'
  // Метод .remove(key) удаляет пару "ключ-значение" по ключу
  contacts.remove('Работа');
  print('Удален контакт: Работа');

  // 4. Удаляем контакт 'Врач'
  contacts.remove('Врач');
  print('Удален контакт: Врач');
  print('');

  // 5. Выводим обновленный список контактов
  // После удаления в Map остались только 3 контакта
  print('Обновленный список:');
  print('Мама: ${contacts['Мама']}');
  print('Папа: ${contacts['Папа']}');
  print('Друг: ${contacts['Друг']}');

  // 6. Выводим количество оставшихся контактов
  // .length автоматически показывает актуальное количество элементов
  print('Всего: ${contacts.length} контакта');
}
