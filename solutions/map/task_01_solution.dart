// Задача 1: Создание первого словаря Map (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем Map с информацией о человеке
  // Map - это коллекция пар "ключ-значение", где каждый ключ уникален
  // Используем фигурные скобки {} для создания Map
  var person = {
    'name': 'Иван',        // ключ 'name' связан со значением 'Иван'
    'age': 20,             // ключ 'age' связан со значением 20
    'city': 'Москва',      // ключ 'city' связан со значением 'Москва'
    'isStudent': true      // ключ 'isStudent' связан со значением true
  };

  // 2. Выводим весь Map целиком
  // При выводе Map показывается в формате {ключ1: значение1, ключ2: значение2, ...}
  print('Информация о человеке: $person');
  print('');

  // 3. Выводим каждое значение по отдельности, обращаясь по ключу
  // Используем квадратные скобки [] для доступа к значению по ключу
  print('Данные по отдельности:');
  print('Имя: ${person['name']}');           // обращаемся к значению по ключу 'name'
  print('Возраст: ${person['age']}');        // обращаемся к значению по ключу 'age'
  print('Город: ${person['city']}');         // обращаемся к значению по ключу 'city'
  print('Студент: ${person['isStudent']}');  // обращаемся к значению по ключу 'isStudent'
  print('');

  // 4. Выводим все ключи Map используя .keys
  // Свойство .keys возвращает коллекцию всех ключей Map
  print('Все ключи: ${person.keys}');

  // 5. Выводим все значения Map используя .values
  // Свойство .values возвращает коллекцию всех значений Map
  print('Все значения: ${person.values}');

  // 6. Выводим количество пар "ключ-значение" используя .length
  // Свойство .length возвращает количество пар в Map
  print('Количество полей: ${person.length}');
}
