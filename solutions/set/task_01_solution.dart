// Задача 1: Создание первого множества Set (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем Set<String> fruits с названиями фруктов
  // Обратите внимание: мы добавляем дубликаты 'яблоко' и 'банан'
  // но Set автоматически оставит только уникальные значения
  var fruits = <String>{'яблоко', 'банан', 'апельсин', 'яблоко', 'киви', 'банан'};

  // 2. Выводим множество
  // Дубликаты автоматически удалены!
  print('Создано множество фруктов: $fruits');

  // 3. Выводим количество элементов
  // .length возвращает количество УНИКАЛЬНЫХ элементов
  print('Количество уникальных фруктов: ${fruits.length}');
  print('(обратите внимание: дубликаты автоматически удалены)');
  print('');

  // 4. Проверяем, содержит ли множество 'яблоко'
  // .contains() возвращает true если элемент есть в множестве
  print('Проверки:');
  print('Есть яблоко: ${fruits.contains('яблоко')}');

  // 5. Проверяем, содержит ли множество 'груша'
  // Вернет false, так как груши нет в множестве
  print('Есть груша: ${fruits.contains('груша')}');
  print('');

  // 6. Добавляем новый фрукт 'манго'
  // .add() добавляет элемент в множество
  fruits.add('манго');
  print('Добавлен новый фрукт: манго');
  print('Множество: $fruits');
  print('');

  // 7. Попытка добавить 'яблоко' снова
  // Set НЕ добавит дубликат - множество не изменится
  print('Попытка добавить яблоко снова...');
  fruits.add('яблоко');
  print('Множество не изменилось: $fruits');
}
