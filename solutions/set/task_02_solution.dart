// Задача 2: Добавление и удаление элементов Set (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем пустой Set<int>
  // Используем <int>{} для создания пустого множества целых чисел
  var numbers = <int>{};

  // 2. Добавляем числа по одному и выводим результат после каждого добавления
  print('Добавление элементов:');

  // Добавляем 10 - первый элемент
  numbers.add(10);
  print('Добавлено 10: $numbers');

  // Добавляем 20
  numbers.add(20);
  print('Добавлено 20: $numbers');

  // Добавляем 30
  numbers.add(30);
  print('Добавлено 30: $numbers');

  // Добавляем 10 снова - дубликат будет проигнорирован
  numbers.add(10);
  print('Добавлено 10: $numbers (дубликат проигнорирован)');

  // Добавляем 40
  numbers.add(40);
  print('Добавлено 40: $numbers');

  // Добавляем 20 снова - дубликат будет проигнорирован
  numbers.add(20);
  print('Добавлено 20: $numbers (дубликат проигнорирован)');
  print('');

  // 4. Добавляем сразу несколько элементов
  // .addAll() принимает список элементов и добавляет их все
  numbers.addAll([50, 60, 70]);
  print('Добавлено несколько: [50, 60, 70]');
  print('Множество: $numbers');
  print('');

  // 5. Удаляем число 30
  // .remove() удаляет элемент из множества
  numbers.remove(30);
  print('Удалено: 30');

  // 6. Попытка удалить число 100 (которого нет)
  // .remove() не выдаст ошибку, просто ничего не произойдет
  numbers.remove(100);
  print('Попытка удалить 100: элемент не найден');
  print('');

  // 7. Выводим финальное множество и его размер
  print('Финальное множество: $numbers');
  print('Размер: ${numbers.length} элементов');
}
