// Задача 3: Константы с const (Легкая) - РЕШЕНИЕ

void main() {
  // 1. Создаем константу pi
  const pi = 3.14159;

  // 2. Создаем константу daysInWeek
  const daysInWeek = 7;

  // 3. Создаем константу appName
  const appName = 'Мой первый проект';

  // 4. Создаем переменную radius (это не константа, может меняться)
  var radius = 5;

  // 5. Вычисляем длину окружности по формуле: 2 * pi * radius
  var circumference = 2 * pi * radius;

  // 6. Выводим результаты
  print('Приложение: $appName');
  print('Длина окружности с радиусом $radius: $circumference');

  // Дополнительно: демонстрация что const нельзя изменить
  print('\nКонстанты:');
  print('π = $pi');
  print('Дней в неделе = $daysInWeek');

  // Попытка изменить const вызовет ошибку компиляции:
  // pi = 3.14; // ОШИБКА!

  // Но переменную можно изменить:
  radius = 10;
  print('\nПосле изменения радиуса на $radius:');
  print('Новая длина окружности: ${2 * pi * radius}');
}
