// Задача 8: Множественное объявление переменных (Средняя) - РЕШЕНИЕ

void main() {
  // 1. Объявляем три int переменные в одной строке для RGB цвета
  int red = 255, green = 100, blue = 50;

  // 2. Объявляем три double переменные в одной строке для координат
  double x = 10.5, y = 20.3, z = 15.7;

  // 3. Создаем название цвета
  String colorName = 'Оранжевый';

  // 4. Создаем название точки
  String pointName = 'A';

  // 5. Выводим информацию о цвете в формате RGB
  print('Цвет: $colorName');
  print('RGB: ($red, $green, $blue)');

  // 6. Выводим информацию о координатах точки
  print('\nТочка: $pointName');
  print('Координаты: ($x, $y, $z)');

  // Дополнительно: другие способы множественного объявления
  print('\n=== ДРУГИЕ СПОСОБЫ ===');

  // Способ 1: Объявление без инициализации
  int a, b, c;
  a = 1;
  b = 2;
  c = 3;
  print('a=$a, b=$b, c=$c');

  // Способ 2: Смешанное объявление
  int value1 = 10, value2 = 20, value3;
  value3 = 30;
  print('value1=$value1, value2=$value2, value3=$value3');

  // Демонстрация работы с цветами
  print('\n=== РАБОТА С ЦВЕТАМИ ===');
  print('Красный канал: $red (${(red/255*100).toStringAsFixed(1)}%)');
  print('Зеленый канал: $green (${(green/255*100).toStringAsFixed(1)}%)');
  print('Синий канал: $blue (${(blue/255*100).toStringAsFixed(1)}%)');

  // Демонстрация работы с координатами
  print('\n=== РАСЧЕТЫ С КООРДИНАТАМИ ===');
  double distanceFromOrigin = (x * x + y * y + z * z);
  print('Расстояние от начала координат (квадрат): ${distanceFromOrigin.toStringAsFixed(2)}');

  // Создание других цветов множественным объявлением
  print('\n=== ДРУГИЕ ЦВЕТА ===');
  int r1 = 255, g1 = 0, b1 = 0; // Красный
  print('Красный: RGB($r1, $g1, $b1)');

  int r2 = 0, g2 = 255, b2 = 0; // Зеленый
  print('Зеленый: RGB($r2, $g2, $b2)');

  int r3 = 0, g3 = 0, b3 = 255; // Синий
  print('Синий: RGB($r3, $g3, $b3)');
}
