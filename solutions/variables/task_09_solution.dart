// Задача 9: Область видимости переменных (Сложная) - РЕШЕНИЕ

void main() {
  // 1. Создаем глобальную (для функции main) переменную totalScore
  var totalScore = 0;
  print('🎮 Начинаем игру! Начальный счет: $totalScore\n');

  // 2. Блок кода для уровня 1
  {
    // Создаем локальную переменную levelScore внутри блока
    var levelScore = 100;

    // Добавляем к общему счету
    totalScore += levelScore;

    // Выводим результат уровня
    print('Уровень 1 завершен! Заработано: $levelScore очков');
    print('Текущий счет: $totalScore\n');
  }
  // После закрывающей скобки переменная levelScore больше не существует

  // 3. Блок кода для уровня 2
  {
    // Можем снова использовать имя levelScore, это другая переменная
    var levelScore = 150;

    totalScore += levelScore;

    print('Уровень 2 завершен! Заработано: $levelScore очков');
    print('Текущий счет: $totalScore\n');
  }

  // 4. Блок кода для уровня 3
  {
    var levelScore = 200;

    totalScore += levelScore;

    print('Уровень 3 завершен! Заработано: $levelScore очков');
    print('Текущий счет: $totalScore\n');
  }

  // 5. Выводим итоговый счет
  print('=====================================');
  print('ИТОГО: $totalScore очков');
  print('=====================================\n');

  // 6. Попробуйте раскомментировать следующую строку:
  // print(levelScore); // Что произойдет?

  // ОШИБКА! Переменная levelScore не существует в этой области видимости.
  // Она была объявлена внутри блоков {} и "умерла" после закрывающей скобки.

  print('📚 Объяснение:');
  print('Переменная levelScore существовала только внутри каждого блока {}');
  print('После закрывающей скобки } переменная уничтожается');
  print('Поэтому за пределами блоков мы не можем обратиться к levelScore\n');

  // ОТВЕТ: Почему мы можем использовать имя levelScore в каждом блоке?
  print('💡 ОТВЕТ НА ВОПРОС:');
  print('Мы можем использовать одинаковое имя "levelScore" в каждом блоке,');
  print('потому что каждый блок {} создает свою собственную область видимости.');
  print('Переменные в разных блоках - это совершенно разные переменные,');
  print('которые никак не связаны друг с другом, даже если имеют одинаковое имя.');
  print('Это как комнаты в доме - в каждой комнате может быть свой стул,');
  print('и они не мешают друг другу, хотя все называются "стул".\n');

  // Дополнительный пример для понимания
  print('🔍 Дополнительный пример:');

  var outerVariable = 'Я доступна везде в main';

  {
    print('Блок А: $outerVariable'); // Можем использовать внешнюю переменную
    var innerVariable = 'Я только в блоке А';
    print('Блок А: $innerVariable');
  }

  {
    print('Блок Б: $outerVariable'); // Внешняя переменная все еще доступна
    var innerVariable = 'Я только в блоке Б'; // Другая переменная с тем же именем!
    print('Блок Б: $innerVariable');
  }

  // print(innerVariable); // ОШИБКА! innerVariable не существует здесь

  print('\n✅ Правила области видимости:');
  print('1. Переменные объявленные в main доступны во всех вложенных блоках');
  print('2. Переменные из блока {} доступны только внутри этого блока');
  print('3. После } переменная из блока "умирает" (удаляется из памяти)');
  print('4. В разных блоках можно использовать одинаковые имена переменных');
}
